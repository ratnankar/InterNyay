-- Dropdown options that used to be hard-coded in the app (case catalogue, client types, document types, ...).
-- The Admin panel (Dropdown Options) edits this table. 'locked' rows are used by the code and cannot be deleted or hidden.
CREATE TABLE option_items (
  id         BIGINT       NOT NULL AUTO_INCREMENT,
  list_key   VARCHAR(40)  NOT NULL,
  parent     VARCHAR(300) NOT NULL DEFAULT '',
  value      VARCHAR(255) NOT NULL,
  label      VARCHAR(255) NOT NULL,
  sort_order INT          NOT NULL DEFAULT 0,
  enabled    BIT(1)       NOT NULL DEFAULT 1,
  locked     BIT(1)       NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY uk_option_items (list_key, parent, value),
  KEY idx_option_items_list (list_key, parent, sort_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

