  ON p.name_key = LOWER(TRIM(REGEXP_REPLACE(r.judge_name, '[[:space:]]+', ' ')))
 AND j.court = r.court AND j.district = r.district
 AND COALESCE(j.designation, '') = COALESCE(r.designation, '')
