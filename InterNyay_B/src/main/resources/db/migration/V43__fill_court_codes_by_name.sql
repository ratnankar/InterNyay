-- InterNyay V43: fill court codes again, matching on what is really in the database.
-- V42 only matched listings that are exactly as the V30 roster loaded them (same judge, court room and designation).
-- If a listing was edited, or the judge changed since, V42 left it empty. This one is not so strict:
--   1. the same room / designation matching as V42 (listings V42 already filled are not touched),
--   2. a judge's name inside its district: when the portal list has that judge once in the district and the judge has
--      one active listing there, the code is filled whatever the room number or designation is,
--   3. a judge with several portal rows (evening courts, in-charge courts): the listing whose designation matches.
-- The court code is the portal value (group^code, e.g. 1^4, posted as CL_court_no). Source: judge_codes_delhi_gurugram.pdf,
-- eCourts Court Name dropdown, 25 Oct 2026. Gurugram has no court in the courts table, so it is not loaded.
-- A listing that already has a court code is never changed. V42 stays as it is (already applied databases keep its checksum).

