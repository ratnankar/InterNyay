-- Judges that appear once in a district of the portal list
DROP TEMPORARY TABLE IF EXISTS tmp_portal_single;
CREATE TEMPORARY TABLE tmp_portal_single ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci AS
SELECT court, district, name_norm, MIN(court_code) AS court_code
FROM tmp_portal_codes
GROUP BY court, district, name_norm
HAVING COUNT(*) = 1;

-- Active listings of a judge in a district, with their name in the same form
DROP TEMPORARY TABLE IF EXISTS tmp_listing_names;
CREATE TEMPORARY TABLE tmp_listing_names ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci AS
SELECT j.id AS judge_id, (j.court COLLATE utf8mb4_unicode_ci) AS court, (j.district COLLATE utf8mb4_unicode_ci) AS district,
       (LOWER(REGEXP_REPLACE(REGEXP_REPLACE(REGEXP_REPLACE(LOWER(p.name), '\\([^)]*\\)', ''), '\\b(sh|smt|ms|mr|mrs|dr|hon|ld|shri|sri|miss)\\b\\.?', ''), '[^a-z]', ''))) COLLATE utf8mb4_unicode_ci AS name_norm,
       (LOWER(REGEXP_REPLACE(COALESCE(j.designation, ''), '[^a-zA-Z0-9]', '')) COLLATE utf8mb4_unicode_ci) AS desig_norm
FROM judges j JOIN judge_profiles p ON p.id = j.profile_id
WHERE j.active = TRUE AND j.court_code IS NULL AND p.vacant = FALSE;

DROP TEMPORARY TABLE IF EXISTS tmp_listing_count;
CREATE TEMPORARY TABLE tmp_listing_count ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci AS
SELECT court, district, name_norm, COUNT(*) AS n FROM tmp_listing_names GROUP BY court, district, name_norm;

-- Step 2: one portal row for the judge in the district and one active listing there
UPDATE judges j
JOIN tmp_listing_names l ON l.judge_id = j.id
JOIN tmp_listing_count c ON c.court = l.court AND c.district = l.district AND c.name_norm = l.name_norm AND c.n = 1
JOIN tmp_portal_single s ON s.court = l.court AND s.district = l.district AND s.name_norm = l.name_norm
SET j.court_code = s.court_code
WHERE j.court_code IS NULL;

