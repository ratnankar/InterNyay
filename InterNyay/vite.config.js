import { defineConfig, loadEnv } from 'vite'
import react from '@vitejs/plugin-react'
import { VitePWA } from 'vite-plugin-pwa'
import { AUTH_PATHS, NAV_IDS, NAV_SLUGS } from './src/routes/paths.js'

// Every address the app answers to, built from the same lists the router uses (src/routes/paths.js), so a new page
// is picked up here without a second edit. Pages with an id behind them (/cases/12, /forms/fill/3) get a trailing /*
const APP_PATHS = [
  '/home', ...Object.values(AUTH_PATHS), '/admin',
  ...NAV_IDS.flatMap(id => (NAV_SLUGS[id] ? [`/${id}`, `/${NAV_SLUGS[id]}`] : [`/${id}`])),
]
const APP_PATH_PREFIXES = ['/admin', '/cases', '/clients', '/forms']

// Pages that need an account (kept out of search engines): everything except the landing page
const PRIVATE_PATHS = APP_PATHS.filter(path => path !== '/home')

// Host rule file (Netlify and Cloudflare Pages both read it): the known addresses get the app (index.html, status 200),
// every other address falls through to 404.html and is answered with a real 404 status instead of a soft 404
function redirectRules() {
  const rules = [...APP_PATHS, ...APP_PATH_PREFIXES.map(p => `${p}/*`)]
  const width = Math.max(...rules.map(r => r.length)) + 2
  return [
    '# Generated by vite.config.js: the addresses the app serves. Anything else gets 404.html with a 404 status.',
    ...rules.map(r => `${r.padEnd(width)}/index.html  200`),
    '',
  ].join('\n')
}

function siteFiles(siteUrl) {
  return {
    name: 'internyay-site-files',
    transformIndexHtml: html => html.replaceAll('__SITE_URL__', siteUrl),
    generateBundle() {
      const robots = [
        'User-agent: *',
        ...PRIVATE_PATHS.map(path => `Disallow: ${path}`),
        `Sitemap: ${siteUrl}/sitemap.xml`,
        '',
      ].join('\n')
      const sitemap = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
        `  <url><loc>${siteUrl}/</loc></url>`,
        '</urlset>',
        '',
      ].join('\n')
      this.emitFile({ type: 'asset', fileName: 'robots.txt', source: robots })
      this.emitFile({ type: 'asset', fileName: 'sitemap.xml', source: sitemap })
      this.emitFile({ type: 'asset', fileName: '_redirects', source: redirectRules() })
    },
  }
}

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), 'VITE_')
  if (mode === 'production') {
    const api = env.VITE_API_BASE_URL || ''
    if (!/^https:\/\//.test(api) || /localhost|127\.0\.0\.1/.test(api)) {
      throw new Error(
        'Production build stopped: set VITE_API_BASE_URL in .env to your live https API address, ' +
        'for example https://api.yourdomain.com/api (currently: "' + api + '")')
    }
    const site = env.VITE_SITE_URL || ''
    if (!/^https:\/\//.test(site) || /localhost|127\.0\.0\.1/.test(site)) {
      throw new Error(
        'Production build stopped: set VITE_SITE_URL in .env to your live https website address, ' +
        'for example https://www.yourdomain.com (currently: "' + site + '")')
    }
  }
  const siteUrl = (env.VITE_SITE_URL || 'http://localhost:5173').replace(/\/+$/, '')
  return {
    plugins: [
      react(),
      siteFiles(siteUrl),
      VitePWA({
        registerType: 'autoUpdate',
        manifest: false,
        workbox: {
          globPatterns: ['**/*.{js,css,html,woff2,svg,webp,png}'],
          globIgnores: ['**/pdf.worker*'],
          navigateFallback: '/index.html',
          navigateFallbackDenylist: [/^\/api/],
          runtimeCaching: [
            { urlPattern: ({ url }) => url.pathname.startsWith('/api'), handler: 'NetworkOnly' },
          ],
        },
      }),
    ],
    test: { environment: 'jsdom', globals: true, include: ['src/**/*.test.{js,jsx}'] },
  }
})
